#!/usr/bin/env python3
"""Assemble every asm/*.s into pokeldn/frlg/rom/buffer_payloads.py.

    ./scripts/gen_buffer_scripts.py [--check]

The bytes are committed so a live host needs no GBA toolchain; tests/test_buffer_script.py
re-assembles and compares when arm-none-eabi-as is installed.
"""

import argparse
import hashlib
import pathlib
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from pokeldn.frlg.rom import custom_code  # noqa: E402

ASM_DIR = ROOT / "asm"
OUT = ROOT / "pokeldn" / "frlg" / "rom" / "buffer_payloads.py"


def assemble(source_path):
    """Assemble one ARM source to raw bytes. Raises CodeError without a toolchain."""
    return custom_code.assemble(source_path.read_text())


def assemble_fixed(source_path, address):
    """Assemble and link the resident PokeHax body at its fixed EWRAM address."""
    tools = custom_code.toolchain()
    if tools is None:
        return assemble(source_path)
    linker = pathlib.Path(tools[0]).with_name("arm-none-eabi-ld.exe" if sys.platform == "win32"
                                               else "arm-none-eabi-ld")
    with tempfile.TemporaryDirectory() as tmp:
        obj = pathlib.Path(tmp) / "pokehax.o"
        elf = pathlib.Path(tmp) / "pokehax.elf"
        binary = pathlib.Path(tmp) / "pokehax.bin"
        subprocess.run([tools[0], *custom_code.AS_FLAGS, "-o", str(obj), str(source_path)], check=True)
        subprocess.run([str(linker), f"-Ttext=0x{address:08x}", "-o", str(elf), str(obj)], check=True)
        subprocess.run([tools[1], "-O", "binary", str(elf), str(binary)], check=True)
        return binary.read_bytes()


def render():
    pokehax_source = ASM_DIR / "pokehax-screen.s"
    pokehax_body = assemble_fixed(pokehax_source, 0x0201C800)
    # The interactive menu is larger than one receive buffer. Bounded RAM-only lead payloads copy
    # this body above the 1 KiB receive image; a tiny trampoline calls it once per frame.
    pokehax_trampoline = bytes.fromhex("00309fe513ff2fe100c80102")
    lines = [
        '"""Generated by scripts/gen_buffer_scripts.py from asm/*.s. Do not edit by hand."""',
        "",
        f"POKEHAX_SCREEN_BODY = bytes.fromhex({pokehax_body.hex()!r})",
        f"POKEHAX_SCREEN_TRAMPOLINE = bytes.fromhex({pokehax_trampoline.hex()!r})",
        f"POKEHAX_SCREEN_SOURCE_SHA256 = {hashlib.sha256(pokehax_source.read_bytes()).hexdigest()!r}",
        "",
        "# name -> (ARM machine code, sha256 of the asm source it was assembled from)",
        "PAYLOADS = {",
    ]
    for source in sorted(ASM_DIR.glob("*.s")):
        if source == pokehax_source:
            continue
        code = assemble(source)
        digest = hashlib.sha256(source.read_bytes()).hexdigest()
        lines.append(f"    {source.stem!r}: (")
        lines.append(f"        bytes.fromhex({code.hex()!r}),")
        lines.append(f"        {digest!r},")
        lines.append("    ),")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="exit non-zero if the committed module is stale")
    args = parser.parse_args()
    text = render()
    if args.check:
        current = OUT.read_text() if OUT.exists() else ""
        if current != text:
            print(f"{OUT} is stale; re-run ./scripts/gen_buffer_scripts.py", file=sys.stderr)
            return 1
        print(f"{OUT} is up to date")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
