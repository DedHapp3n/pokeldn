#!/usr/bin/env python3
"""Assemble every asm/*.s into pokeldn/frlg/rom/buffer_payloads.py.

    ./scripts/gen_buffer_scripts.py [--check]

The bytes are committed so a live host needs no GBA toolchain; tests/test_buffer_script.py
re-assembles and compares when arm-none-eabi-as is installed.
"""

import argparse
import hashlib
import pathlib
import re
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from pokeldn.frlg.rom import builds, custom_code, native_script  # noqa: E402

ASM_DIR = ROOT / "asm"
OUT = ROOT / "pokeldn" / "frlg" / "rom" / "buffer_payloads.py"
ANDROID_OUT = (ROOT / "android" / "app" / "src" / "main" / "java" / "com" / "dedhapp3n" /
               "pokeldn" / "frlg" / "PokeHaxScreenPayload.kt")


def source_digest(path):
    """Hash assembler text independent of Git's checkout line-ending policy."""
    source = path.read_bytes().replace(b"\r\n", b"\n").replace(b"\r", b"\n")
    return hashlib.sha256(source).hexdigest()


def assemble(source_path):
    """Assemble one ARM source to raw bytes. Raises CodeError without a toolchain."""
    return custom_code.assemble(source_path.read_text())


def assemble_fixed(source_path, address):
    """Assemble and link the resident PokeHax body at its fixed EWRAM address."""
    tools = custom_code.toolchain()
    if tools is None:
        return assemble(source_path)
    linker = pathlib.Path(tools[0]).with_name("arm-none-eabi-ld.exe" if sys.platform == "win32"
                                               else "arm-none-eabi-ld")
    with tempfile.TemporaryDirectory() as tmp:
        obj = pathlib.Path(tmp) / "pokehax.o"
        elf = pathlib.Path(tmp) / "pokehax.elf"
        binary = pathlib.Path(tmp) / "pokehax.bin"
        subprocess.run([tools[0], *custom_code.AS_FLAGS, "-o", str(obj), str(source_path)], check=True)
        subprocess.run([str(linker), f"-Ttext=0x{address:08x}", "-o", str(elf), str(obj)], check=True)
        subprocess.run([tools[1], "-O", "binary", str(elf), str(binary)], check=True)
        return binary.read_bytes()


def build_pokehax():
    pokehax_source = ASM_DIR / "pokehax-screen.s"
    pokehax_body = assemble_fixed(pokehax_source, 0x0201C800)
    # The interactive menu is larger than one receive buffer. Bounded RAM-only lead payloads copy
    # this body above the 1 KiB receive image; a tiny trampoline calls it once per frame.
    pokehax_trampoline = bytes.fromhex("00309fe513ff2fe100c80102")
    loader = bytearray(assemble(ASM_DIR / "field" / "pokehax-loader.s"))
    build = builds.resolve("BPGD")
    loader = loader.replace((0x03002730).to_bytes(4, "little"),
                            build.intr_vblank.to_bytes(4, "little"))
    field_script = native_script.build_body_script(loader, bytes([native_script.SCR_END]),
                                                   build=build)
    installer = bytearray(assemble(ASM_DIR / "pokehax-install.s"))
    body_size_at = installer.index((0xBBBBBBBB).to_bytes(4, "little"))
    sb1_at = installer.index((0xAAAAAAAA).to_bytes(4, "little"))
    crc_at = installer.index((0xCCCCCCCC).to_bytes(4, "little"))
    script_size_at = installer.index((0xDDDDDDDD).to_bytes(4, "little"))
    script_at = installer.index(bytes([0xEE]) * 32)
    if len(field_script) > 720:
        raise RuntimeError(f"persistent PokeHax field script is {len(field_script)} bytes, max 720")
    installer[body_size_at:body_size_at + 4] = len(pokehax_body).to_bytes(4, "little")
    installer[sb1_at:sb1_at + 4] = build.sb1ptr.to_bytes(4, "little")
    installer[script_size_at:script_size_at + 4] = len(field_script).to_bytes(4, "little")
    installer[script_at:script_at + len(field_script)] = field_script
    installer[script_at + len(field_script):script_at + 720] = bytes(720 - len(field_script))
    return (pokehax_source, pokehax_body, pokehax_trampoline, bytes(installer),
            script_at, len(field_script), crc_at)


def render(pokehax_source, pokehax_body, pokehax_trampoline, installer,
           installer_script_at, installer_script_size, installer_crc_at):
    lines = [
        '"""Generated by scripts/gen_buffer_scripts.py from asm/*.s. Do not edit by hand."""',
        "",
        f"POKEHAX_SCREEN_BODY = bytes.fromhex({pokehax_body.hex()!r})",
        f"POKEHAX_SCREEN_TRAMPOLINE = bytes.fromhex({pokehax_trampoline.hex()!r})",
        f"POKEHAX_INSTALLER = bytes.fromhex({installer.hex()!r})",
        f"POKEHAX_INSTALLER_SCRIPT_AT = {installer_script_at}",
        f"POKEHAX_INSTALLER_SCRIPT_SIZE = {installer_script_size}",
        f"POKEHAX_INSTALLER_CRC_AT = {installer_crc_at}",
        f"POKEHAX_SCREEN_SOURCE_SHA256 = {source_digest(pokehax_source)!r}",
        "",
        "# name -> (ARM machine code, sha256 of the asm source it was assembled from)",
        "PAYLOADS = {",
    ]
    for source in sorted(ASM_DIR.glob("*.s")):
        if source == pokehax_source:
            continue
        code = assemble(source)
        digest = source_digest(source)
        lines.append(f"    {source.stem!r}: (")
        lines.append(f"        bytes.fromhex({code.hex()!r}),")
        lines.append(f"        {digest!r},")
        lines.append("    ),")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def render_android(current, pokehax_body, installer, script_at, script_size, crc_at):
    """Replace only generated byte literals in Android's transfer wrapper."""
    updated = current
    for name, data in (("baseBody", pokehax_body), ("baseInstaller", installer)):
        chunks = [data.hex()[at:at + 120] for at in range(0, len(data) * 2, 120)]
        literal = f"    private val {name} = (\n" + "\n".join(
            f'        "{chunk}"' + (" +" if index + 1 < len(chunks) else "")
            for index, chunk in enumerate(chunks)
        ) + "\n    ).hexBytesScreen()"
        pattern = rf"    private val {name} = \(\n.*?\n    \)\.hexBytesScreen\(\)"
        updated, count = re.subn(pattern, literal, updated, count=1, flags=re.DOTALL)
        if count != 1:
            raise RuntimeError(f"could not find Android {name} in {ANDROID_OUT}")
    for name, value in (("INSTALLER_SCRIPT_AT", script_at),
                        ("INSTALLER_SCRIPT_SIZE", script_size), ("INSTALLER_CRC_AT", crc_at)):
        updated, count = re.subn(rf"(private const val {name} = )\d+", rf"\g<1>{value}", updated)
        if count != 1:
            raise RuntimeError(f"could not find Android {name} in {ANDROID_OUT}")
    return updated


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="exit non-zero if the committed module is stale")
    args = parser.parse_args()
    built = build_pokehax()
    pokehax_source, pokehax_body, pokehax_trampoline, installer, script_at, script_size, crc_at = built
    text = render(*built)
    android_current = ANDROID_OUT.read_text()
    android_text = render_android(android_current, pokehax_body, installer,
                                  script_at, script_size, crc_at)
    if args.check:
        current = OUT.read_text() if OUT.exists() else ""
        stale = [str(path) for path, before, after in (
            (OUT, current, text), (ANDROID_OUT, android_current, android_text)) if before != after]
        if stale:
            print(f"{', '.join(stale)} is stale; re-run ./scripts/gen_buffer_scripts.py",
                  file=sys.stderr)
            return 1
        print(f"{OUT} and {ANDROID_OUT} are up to date")
        return 0
    OUT.write_text(text)
    ANDROID_OUT.write_text(android_text)
    print(f"wrote {OUT} and {ANDROID_OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
