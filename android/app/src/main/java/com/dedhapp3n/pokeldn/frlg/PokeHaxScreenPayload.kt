    private fun body(layout: Layout) = baseBody.copyOf().also {
            it.replaceWords(0x020375f4, layout.palette - 0x3e2)
            it.replaceWords(0x020371f4, layout.palette - 0x7e2)
            it.replaceWords(0x03004220, layout.rng)
            it.replaceWords(0x030022d0, layout.gmain)
            it.replaceWords(0x03004228, layout.save1Ptr)
            it.replaceWords(0x02024280, layout.party)
            it.replaceWords(0x02037074, layout.avatar)
            it.replaceWords(0x02036e34, layout.objects)
        }

    private fun transfer(layout: Layout, payload: ByteArray): FrlgBufferTransfer {
        val body = body(layout)
        val leads = body.asList().chunked(CHUNK_BYTES).mapIndexed { index, bytes ->
            copyHeader.copyOf().also {
                it.putLe32Screen(4, BODY_ADDRESS + index * CHUNK_BYTES)
                it.putLe32Screen(8, bytes.size)
            } + bytes.toByteArray()
        }
        require(leads.all { it.size <= 1024 } && payload.size <= 1024)
        return FrlgBufferTransfer(leads, payload)
    }

    fun forGameCode(code: String): FrlgBufferTransfer? = layouts[code]?.let {
        transfer(it, trampoline.copyOf())
    }

    fun installerForGameCode(code: String): FrlgBufferTransfer? = layouts[code]?.let { layout ->
        val installer = baseInstaller.copyOf().also {
            it.replaceWords(0x03002730, layout.vblankTable)
            it.replaceWords(0x03004228, layout.save1Ptr)
        }
        val data = ByteArray(1000)
        data[0] = 51
        data[1] = 4
        data[2] = 0
        data[3] = 1
        installer.copyInto(data, 4, INSTALLER_SCRIPT_AT,
            INSTALLER_SCRIPT_AT + INSTALLER_SCRIPT_SIZE)
        installer.putLe32Screen(INSTALLER_CRC_AT, crc16Screen(data))
        transfer(layout, installer)
    }
